CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nim VARCHAR(20) NOT NULL UNIQUE CHECK (nim ~ '^[0-9]{4,20}$'),
  full_name VARCHAR(120) NOT NULL,
  password_hash TEXT NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE SEQUENCE IF NOT EXISTS report_case_number_seq;

CREATE TABLE IF NOT EXISTS reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_number VARCHAR(32) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  title VARCHAR(160) NOT NULL,
  category VARCHAR(60) NOT NULL,
  incident_date DATE NOT NULL,
  chronology VARCHAR(2000) NOT NULL,
  is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(16) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  decision_note VARCHAR(2000),
  decided_by BIGINT REFERENCES users(id),
  decided_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (status = 'pending' AND decided_by IS NULL AND decided_at IS NULL)
    OR (status <> 'pending' AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS reports_user_created_idx
  ON reports (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS reports_status_created_idx
  ON reports (status, created_at ASC);

CREATE TABLE IF NOT EXISTS report_attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  storage_name VARCHAR(80) NOT NULL UNIQUE,
  original_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(80) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  body VARCHAR(3000) NOT NULL,
  category VARCHAR(32) NOT NULL DEFAULT 'Informasi Umum'
    CHECK (category IN ('Akademik', 'Kemahasiswaan', 'Beasiswa', 'Kegiatan Kampus', 'Informasi Umum')),
  is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  published_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (is_published = FALSE AND published_at IS NULL)
    OR (is_published = TRUE AND published_at IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS announcements_published_idx
  ON announcements (published_at DESC)
  WHERE is_published = TRUE;
CREATE INDEX IF NOT EXISTS announcements_active_order_idx
  ON announcements (is_pinned DESC, published_at DESC, expires_at)
  WHERE is_published = TRUE;

CREATE TABLE IF NOT EXISTS auth_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS auth_attempts_ip_created_idx
  ON auth_attempts (ip_hash, created_at DESC);
